/* Generates a 64x64 blue noise threshold mask using the void-and-cluster algorithm
   (Ulichney, 1993), and writes it to data/bluenoise.js as a base64 string.
   Run: node build/bluenoise.js */
"use strict";
const fs = require("fs");
const path = require("path");

const SIZE = 64;
const N = SIZE * SIZE;
const SIGMA = 1.9;

/* gaussian kernel offsets (torus wrap) */
const R = Math.ceil(SIGMA * 3);
const kernel = [];
for (let dy = -R; dy <= R; dy++) {
  for (let dx = -R; dx <= R; dx++) {
    kernel.push([dx, dy, Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA))]);
  }
}

const filtered = new Float64Array(N);
const binary = new Uint8Array(N);
const wrap = (v) => ((v % SIZE) + SIZE) % SIZE;
const idx = (x, y) => wrap(y) * SIZE + wrap(x);

function toggle(x, y, add) {
  const sign = add ? 1 : -1;
  for (let k = 0; k < kernel.length; k++) {
    const [dx, dy, w] = kernel[k];
    filtered[idx(x + dx, y + dy)] += sign * w;
  }
}

function tightestCluster() {
  let best = -1;
  let bestV = -Infinity;
  for (let i = 0; i < N; i++) {
    if (binary[i] && filtered[i] > bestV) {
      bestV = filtered[i];
      best = i;
    }
  }
  return best;
}

function largestVoid() {
  let best = -1;
  let bestV = Infinity;
  for (let i = 0; i < N; i++) {
    if (!binary[i] && filtered[i] < bestV) {
      bestV = filtered[i];
      best = i;
    }
  }
  return best;
}

/* deterministic PRNG */
let seed = 0x2f6e2b1;
function rnd() {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  return seed / 0x7fffffff;
}

console.log("1/4  initial random pattern...");
for (let i = 0; i < N; i++) {
  if (rnd() < 0.5) {
    binary[i] = 1;
    toggle(i % SIZE, Math.floor(i / SIZE), true);
  }
}

console.log("2/4  optimising initial pattern (cluster/void swaps)...");
for (let iter = 0; iter < 200000; iter++) {
  const c = tightestCluster();
  binary[c] = 0;
  toggle(c % SIZE, Math.floor(c / SIZE), false);
  const v = largestVoid();
  if (v === c) {
    binary[c] = 1;
    toggle(c % SIZE, Math.floor(c / SIZE), true);
    break;
  }
  binary[v] = 1;
  toggle(v % SIZE, Math.floor(v / SIZE), true);
}

const ones = binary.reduce((a, b) => a + b, 0);
console.log("     initial pattern ones:", ones);

/* remember the prototype pattern (needed to restore before phase 2) */
const proto = Uint8Array.from(binary);

const rank = new Int32Array(N).fill(-1);

console.log("3/4  ranking (phase 1: remove tightest clusters)...");
let r = ones - 1;
while (r >= 0) {
  const c = tightestCluster();
  binary[c] = 0;
  toggle(c % SIZE, Math.floor(c / SIZE), false);
  rank[c] = r;
  r--;
}

console.log("4/4  ranking (phase 2: restore pattern, then fill largest voids)...");
/* restore the prototype pattern (binary + filtered) */
binary.fill(0);
filtered.fill(0);
for (let i = 0; i < N; i++) {
  if (proto[i]) {
    binary[i] = 1;
    toggle(i % SIZE, Math.floor(i / SIZE), true);
  }
}
r = ones;
while (r < N) {
  const v = largestVoid();
  binary[v] = 1;
  toggle(v % SIZE, Math.floor(v / SIZE), true);
  rank[v] = r;
  r++;
}

/* sanity: ranks must be a permutation of 0..N-1 */
const seen = new Uint8Array(N);
let bad = 0;
for (let i = 0; i < N; i++) {
  if (rank[i] < 0 || rank[i] >= N || seen[rank[i]]) bad++;
  seen[rank[i]] = 1;
}
if (bad > 0) {
  console.error("ERROR: rank matrix is not a permutation, bad entries:", bad);
  process.exit(1);
}

/* normalise to 0..255 */
const bytes = new Uint8Array(N);
for (let i = 0; i < N; i++) bytes[i] = Math.floor((rank[i] * 256) / N);

/* quality metric: average low-frequency energy (should be low for blue noise) */
const mean = bytes.reduce((a, b) => a + b, 0) / N;
let localAvgDev = 0;
for (let y = 0; y < SIZE; y++) {
  for (let x = 0; x < SIZE; x++) {
    let s = 0;
    for (let dy = -2; dy <= 2; dy++) for (let dx = -2; dx <= 2; dx++) s += bytes[idx(x + dx, y + dy)];
    localAvgDev += Math.abs(s / 25 - mean);
  }
}
console.log("     mask mean:", mean.toFixed(1), "| mean local deviation:", (localAvgDev / N).toFixed(1), "(blue noise ~ small)");

const b64 = Buffer.from(bytes).toString("base64");
const out = `/* Generated by build/bluenoise.js - 64x64 blue noise threshold mask (void-and-cluster).
   Values 0..255, use as an ordered dithering threshold matrix. */
window.BLUE_NOISE_64 = { size: ${SIZE}, data: "${b64}" };
`;
const outPath = path.join(__dirname, "..", "data", "bluenoise.js");
fs.writeFileSync(outPath, out);
console.log("written:", outPath, "(" + out.length + " bytes)");
